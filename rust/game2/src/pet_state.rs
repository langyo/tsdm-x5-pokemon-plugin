mod tests {
    use super::*;

    #[test]
    fn healthy_state_has_no_modifiers() {
        assert_eq!(describe(1), "状态良好");
    }

    #[test]
    fn debuff_lists_negative_percentages() {
        let text = describe(4);
        assert!(text.starts_with("病情严重"));
        assert!(text.contains("HP -50%"));
    }

    #[test]
    fn unknown_state_yields_empty() {
        assert_eq!(describe(200), "");
    }
}
