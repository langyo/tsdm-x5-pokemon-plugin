const STAT_NAMES: [&str; 6] = ["HP", "攻击", "防御", "特攻", "特防", "速度"];

/// 某状态码的完整说明（描述 + 非中性的属性增减），用于 title 悬浮。
pub fn describe(state: u8) -> String {
    let Some((_, desc, mults)) = STATES.iter().find(|(code, _, _)| *code == state) else {
        return String::new();
    };
    let mut parts: Vec<String> = Vec::new();
    for (i, mult) in mults.iter().enumerate() {
        if (mult - 1.0).abs() < 0.01 {
            continue;
        }
        let pct = ((mult - 1.0) * 100.0).abs().round() as i32;
        let sign = if *mult > 1.0 { '+' } else { '-' };
        parts.push(format!("{} {sign}{pct}%", STAT_NAMES[i]));
    }
    if parts.is_empty() {
        desc.to_string()
    } else {
        format!("{desc}\n{}", parts.join("，"))
    }
}

